using System.Collections.Concurrent;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization.Metadata;
using Microsoft.AspNetCore.OpenApi;
using Microsoft.OpenApi;

namespace Reaparr.AppHost;

/// <summary>
/// Keeps CLR enum member names available after FastEndpoints finishes cloning schemas.
/// </summary>
/// <remarks>
/// JSON enum values remain owned by System.Text.Json and may differ from CLR identifiers. This transformer
/// records those identifiers separately, then adds the x-enumNames extension used by client generation.
/// One instance must be registered for both passes, with its document pass after FastEndpoints' schema cloning
/// and after any additional client-only component schemas have been registered.
/// </remarks>
/// <param name="createSchemaReferenceId">
/// The document's component-name policy, used to correlate captured enum metadata with final named schemas.
/// </param>
internal sealed class OpenApiEnumNamesSchemaTransformer(Func<JsonTypeInfo, string?> createSchemaReferenceId)
    : IOpenApiSchemaTransformer,
        IOpenApiDocumentTransformer
{
    private readonly ConcurrentDictionary<string, string[]> _enumNames = new(StringComparer.Ordinal);

    /// <summary>
    /// Captures CLR member names for an enum schema without attaching extensions during schema generation.
    /// </summary>
    /// <param name="schema">The schema being generated; it is deliberately left unchanged during this pass.</param>
    /// <param name="context">The JSON type metadata identifying the enum and its component-name policy input.</param>
    /// <param name="cancellationToken">The pipeline token; this synchronous metadata capture performs no cancellable I/O.</param>
    /// <returns>A completed task after capturing an enum, or immediately when the CLR type is not an enum.</returns>
    /// <remarks>
    /// Nullable enums are inspected through their underlying enum type. Names are indexed by the configured
    /// schema reference ID, falling back to the enum's CLR type name when no ID is supplied. Capturing names
    /// here preserves the distinction between CLR identifiers and custom serialized values without modifying
    /// the enum values generated by the JSON serializer.
    /// </remarks>
    public Task TransformAsync(
        OpenApiSchema schema,
        OpenApiSchemaTransformerContext context,
        CancellationToken cancellationToken
    )
    {
        var enumType = Nullable.GetUnderlyingType(context.JsonTypeInfo.Type) ?? context.JsonTypeInfo.Type;
        if (!enumType.IsEnum)
            return Task.CompletedTask;

        var schemaName = createSchemaReferenceId(context.JsonTypeInfo) ?? enumType.Name;
        _enumNames[schemaName] = enumType.GetEnumNames();

        return Task.CompletedTask;
    }

    /// <summary>
    /// Attaches captured CLR enum names to matching concrete component schemas in the final document.
    /// </summary>
    /// <param name="document">The document whose named enum components receive the x-enumNames extension.</param>
    /// <param name="context">The document pipeline context; captured schema metadata supplies the names for this pass.</param>
    /// <param name="cancellationToken">The pipeline token; updating the in-memory component collection is synchronous.</param>
    /// <returns>A completed task after updating matching components, or immediately when no components exist.</returns>
    /// <remarks>
    /// FastEndpoints cannot clone schema extensions during its earlier document processing, so attaching this
    /// extension during the schema pass would break that processing. The late pass updates only concrete
    /// components with captured names, leaves unrelated components and references alone, and preserves each
    /// enum's existing serialized values.
    /// </remarks>
    public Task TransformAsync(
        OpenApiDocument document,
        OpenApiDocumentTransformerContext context,
        CancellationToken cancellationToken
    )
    {
        if (document.Components?.Schemas is not { } schemas)
            return Task.CompletedTask;

        // FastEndpoints cannot clone schema extensions. Add them only after its document pass.
        foreach (var (name, schema) in schemas)
        {
            if (schema is not OpenApiSchema concreteSchema || !_enumNames.TryGetValue(name, out var names))
                continue;

            var enumNames = new JsonArray();
            foreach (var enumName in names)
                enumNames.Add(JsonValue.Create(enumName));

            concreteSchema.Extensions ??= new Dictionary<string, IOpenApiExtension>();
            concreteSchema.Extensions["x-enumNames"] = new JsonNodeExtension(enumNames);
        }

        return Task.CompletedTask;
    }
}
