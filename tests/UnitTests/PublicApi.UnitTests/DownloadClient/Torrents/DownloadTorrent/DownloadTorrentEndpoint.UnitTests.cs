    [Test]
    public async Task ShouldRejectScalarValidRequest_WhenDataAndPartIdsDiffer()
    {
        // Arrange
        var request = new DownloadTorrentEndpointRequest
        {
            Type = PlexMediaType.Movie,
            MediaId = 1,
            DataId = 1,
            PartId = 2,
            PlexApiPartId = 3,
            VideoQuality = VideoQuality.HD,
            LibraryId = 1,
            ServerId = 1,
        };

        // Act
        var endpointResult = await TestEndpointHandleAsync(request);

        // Assert
        endpointResult.IsValid.ShouldBeFalse();
        endpointResult.ValidationErrors.Count.ShouldBe(1);
        endpointResult
            .ValidationErrors.Single()
            .ErrorMessage.ShouldBe(
                $"{nameof(TorrentMetadataDTO.DataId)} and {nameof(TorrentMetadataDTO.PartId)} must match."
            );
    }

    [Test]
    public async Task ShouldReturnNotFound_WhenMovieMediaIdBelongsToDifferentSource()
    {
        // Arrange
        await SetupDatabase(
            1004,
            config =>
            {
                config.PlexMovieLibraryCount = 1;
                config.MovieCount = 2;
                config.RadarrIntegrationCount = 1;
            }
        );
        var dbContext = IDbContext;
        var integration = await dbContext.RadarrIntegrations.SingleAsync(CancellationToken);
        var movieData = await dbContext.PlexMovieData.OrderBy(x => x.Id).ToArrayAsync(CancellationToken);
        movieData.Length.ShouldBe(2);
        var sourceMovie = movieData[0];
        var otherMovie = movieData[1];
        sourceMovie.PlexLibraryId.ShouldBe(otherMovie.PlexLibraryId);
        sourceMovie.PlexServerId.ShouldBe(otherMovie.PlexServerId);
        sourceMovie.PlexMovieId.ShouldNotBe(otherMovie.PlexMovieId);
        sourceMovie.PlexApiPartId.ShouldNotBe(otherMovie.PlexApiPartId);
        var req = new DownloadTorrentEndpointRequest
        {
            Type = PlexMediaType.Movie,
            MediaId = otherMovie.PlexMovieId,
            DataId = sourceMovie.Id,
            PartId = sourceMovie.Id,
            PlexApiPartId = sourceMovie.PlexApiPartId,
            VideoQuality = sourceMovie.VideoQuality,
            LibraryId = sourceMovie.PlexLibraryId,
            ServerId = sourceMovie.PlexServerId,
        };

        // Act
        var endpointResult = await TestEndpointHandleAsync(req, integrationIdentity: integration.Id.ToRadarrIdentity());

        // Assert
        endpointResult.StatusCode.ShouldBe(StatusCodes.Status404NotFound);
        endpointResult.Endpoint.HttpContext.Response.Body.Length.ShouldBe(0);
    }

    [Test]
