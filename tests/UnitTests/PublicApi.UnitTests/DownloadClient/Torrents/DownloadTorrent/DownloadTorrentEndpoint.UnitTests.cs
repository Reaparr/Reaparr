            {
                config.PlexServerCount = 1;
                config.PlexMovieLibraryCount = 1;
                config.PlexTvShowLibraryCount = 1;
                config.MovieCount = 0;
                config.TvShowCount = 0;
                config.SonarrIntegrationCount = 1;
